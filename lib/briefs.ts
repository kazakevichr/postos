/**
 * Бриф проекта для генерации тем и текстов.
 *
 * У СуперФита и MoneyBall он написан в коде выше — списан с их заводов. Новый
 * проект (Психолог, паблик) получает бриф из анкеты, которая хранится в
 * Setting под ключом brief:<бренд>: так новый проект не требует правки кода.
 * Анкета важнее кода — её человек мог поправить позже.
 */
export async function briefOf(brand: string): Promise<Brief | null> {
  const row = await prisma.setting.findUnique({ where: { key: `brief:${brand}` } });
  if (row) {
    try {
      const b = JSON.parse(row.value);
      if (b?.intro) return { intro: String(b.intro), rules: String(b.rules || ""), hints: b.hints || {} };
    } catch {}
  }
  return BRIEFS[brand] || null;
}
